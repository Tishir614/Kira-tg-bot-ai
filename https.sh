#!/usr/bin/env bash
# Включает HTTPS (Let's Encrypt + nginx) для Mini App / справки Киры.
#
#   bash https.sh kira.example.com you@mail.com        — выпустить сертификат и включить HTTPS
#   bash https.sh kira.example.com you@mail.com --dry-run   — только создать файлы, ничего не запускать
#   bash https.sh --remove                              — выключить HTTPS (сертификаты остаются)
#   флаги: --staging (тестовый сертификат Let's Encrypt), --no-cron (без автопродления)
#
# ГАРАНТИИ: скрипт НЕ читает значение TOKEN, НЕ изменяет .env, НЕ трогает тома с данными бота
# (kira-persistent-data, kira-redis, kira-ollama...) и не использует `down -v`. Всё HTTPS-специфичное
# лежит в отдельных файлах: compose.override.yml и deploy/nginx.generated.conf (оба в .gitignore).
# docker compose подхватывает compose.override.yml автоматически, поэтому deploy.sh/install.sh
# продолжают работать с HTTPS без каких-либо правок.
set -Eeuo pipefail
umask 022

PROJECT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
cd "$PROJECT_DIR"
MARK="# generated by https.sh"
OVERRIDE="compose.override.yml"
CONF_OUT="deploy/nginx.generated.conf"

say() { printf '\033[0;36m[https]\033[0m %s\n' "$*"; }
warn() { printf '\033[1;33m[!]\033[0m %s\n' "$*"; }
die() { printf '\033[0;31m[ERROR]\033[0m %s\n' "$*" >&2; exit 1; }
trap 'die "Ошибка на строке $LINENO. .env, токен и память бота не затронуты. Откат HTTPS: bash https.sh --remove"' ERR

DOMAIN="" EMAIL="" DRY=0 STAGING=0 CRON=1 REMOVE=0
for arg in "$@"; do
  case "$arg" in
    --dry-run) DRY=1 ;;
    --staging) STAGING=1 ;;
    --no-cron) CRON=0 ;;
    --remove)  REMOVE=1 ;;
    -*) die "Неизвестный флаг: $arg" ;;
    *) if [[ -z "$DOMAIN" ]]; then DOMAIN="$arg"; elif [[ -z "$EMAIL" ]]; then EMAIL="$arg"; else die "Лишний аргумент: $arg"; fi ;;
  esac
done

compose() { docker compose "$@"; }

if [[ "$REMOVE" == 1 ]]; then
  if [[ -f "$OVERRIDE" ]] && grep -q "$MARK" "$OVERRIDE"; then
    rm -f "$OVERRIDE" "$CONF_OUT"
    say "Файлы HTTPS удалены."
    if [[ "$DRY" == 0 ]] && command -v docker >/dev/null 2>&1; then
      compose up -d --no-deps kira      # пересоздаёт контейнер без HTTPS-переменных; тома (память бота) остаются
      compose --profile webapp stop nginx 2>/dev/null || true
    fi
    rm -f /etc/cron.d/kira-certbot 2>/dev/null || true
    say "HTTPS выключен. Сертификаты в томе kira-letsencrypt сохранены."
  else
    say "Файла $OVERRIDE от https.sh нет — отключать нечего."
  fi
  exit 0
fi

[[ -n "$DOMAIN" && -n "$EMAIL" ]] || die "Использование: bash https.sh <домен> <email> [--dry-run] [--staging] [--no-cron]"
[[ "$DOMAIN" =~ ^([a-z0-9]([a-z0-9-]*[a-z0-9])?\.)+[a-z]{2,}$ ]] || die "Домен выглядит неверно: $DOMAIN (нужен вид kira.example.com, строчными буквами)"
[[ "$EMAIL" =~ ^[^@[:space:]]+@[^@[:space:]]+\.[^@[:space:]]+$ ]] || die "Email выглядит неверно: $EMAIL"
[[ -f deploy/nginx-https.conf.template && -f compose.yml ]] || die "Запускай из папки проекта (нет compose.yml / шаблона nginx)."
if [[ -f "$OVERRIDE" ]] && ! grep -q "$MARK" "$OVERRIDE"; then
  die "$OVERRIDE уже существует и создан не https.sh. Переименуй его или объедини вручную — я его не перезаписываю."
fi

# ---------- 1. Файлы (всегда; безопасно, без docker) ----------
sed "s/__DOMAIN__/${DOMAIN}/g" deploy/nginx-https.conf.template > "$CONF_OUT"
cat > "$OVERRIDE" <<EOF_OVR
$MARK for ${DOMAIN}. Удалить: bash https.sh --remove
services:
  kira:
    environment:
      KIRA_WEBAPP_URL: https://${DOMAIN}/kira
      DND_WEBAPP_URL: https://${DOMAIN}/dnd
  nginx:
    volumes:
      - ./${CONF_OUT}:/etc/nginx/conf.d/default.conf:ro
      - ./deploy/kira_proxy_headers.conf:/etc/nginx/kira_proxy_headers.conf:ro
      - kira-letsencrypt:/etc/letsencrypt:ro
      - kira-certbot-webroot:/var/www/certbot:ro
volumes:
  kira-letsencrypt:
    name: kira-letsencrypt
  kira-certbot-webroot:
    name: kira-certbot-webroot
EOF_OVR
say "Созданы $CONF_OUT и $OVERRIDE (домен $DOMAIN)."

if [[ "$DRY" == 1 ]]; then
  say "Режим --dry-run: docker не запускался. Дальше: bash https.sh $DOMAIN $EMAIL"
  exit 0
fi

# ---------- 2. Проверки (только чтение) ----------
command -v docker >/dev/null || die "Нужен docker."
docker compose version >/dev/null 2>&1 || die "Нужен docker compose v2."
if [[ -f .env ]] && ! grep -Eq '^WEB_PANEL_ENABLED=1' .env; then
  warn "В .env не WEB_PANEL_ENABLED=1: веб-сервис Киры выключен, Mini App не откроется. Я .env не меняю — включи параметр сам и перезапусти бота."
fi
RESOLVED="$(getent hosts "$DOMAIN" 2>/dev/null | awk '{print $1; exit}' || true)"
PUBLIC_IP="$(curl -fsS -m 6 https://api.ipify.org 2>/dev/null || true)"
if [[ -z "$RESOLVED" ]]; then
  die "Домен $DOMAIN не резолвится. Создай A-запись на IP этого сервера${PUBLIC_IP:+ ($PUBLIC_IP)} и повтори."
elif [[ -n "$PUBLIC_IP" && "$RESOLVED" != "$PUBLIC_IP" ]]; then
  warn "$DOMAIN указывает на $RESOLVED, а публичный IP сервера $PUBLIC_IP. Если это не Cloudflare-прокси/ваш NAT — выпуск сертификата не удастся."
fi

# ---------- 3. Сертификат ----------
CERT_ARGS=(certonly --standalone --preferred-challenges http -d "$DOMAIN" -m "$EMAIL" --agree-tos --no-eff-email -n)
[[ "$STAGING" == 1 ]] && CERT_ARGS+=(--staging)
if docker run --rm -v kira-letsencrypt:/etc/letsencrypt alpine test -s "/etc/letsencrypt/live/$DOMAIN/fullchain.pem" 2>/dev/null; then
  say "Сертификат для $DOMAIN уже есть — выпуск пропущен."
else
  say "Выпускаю сертификат Let's Encrypt (порт 80 должен быть свободен и открыт в файрволе)…"
  compose --profile webapp stop nginx >/dev/null 2>&1 || true
  docker run --rm -p 80:80 -v kira-letsencrypt:/etc/letsencrypt certbot/certbot "${CERT_ARGS[@]}"
fi

# ---------- 4. Запуск: пересоздаются только nginx и kira (тома и память бота сохраняются) ----------
compose config -q
compose --profile webapp up -d --no-deps nginx
compose up -d --no-deps kira
say "Жду ответа HTTPS…"
ok=0
for _ in $(seq 1 20); do
  if curl -fsS -m 5 "https://${DOMAIN}/health" >/dev/null 2>&1; then ok=1; break; fi
  sleep 3
done
if [[ "$ok" == 1 ]]; then
  say "HTTPS работает: https://${DOMAIN}/kira  ·  справка: https://${DOMAIN}/commands"
else
  warn "https://${DOMAIN}/health пока не отвечает. Логи: docker compose --profile webapp logs --tail=50 nginx kira"
  [[ "$STAGING" == 1 ]] && warn "Использован тестовый сертификат (--staging): браузеры/Telegram ему не доверяют."
fi

# ---------- 5. Автопродление ----------
RENEW="cd $PROJECT_DIR && docker run --rm -v kira-letsencrypt:/etc/letsencrypt -v kira-certbot-webroot:/var/www/certbot certbot/certbot renew --webroot -w /var/www/certbot -q && docker compose --profile webapp exec -T nginx nginx -s reload"
# Проверка, что продление реально сработает (тестовый прогон на staging-сервере Let's Encrypt).
if docker run --rm -v kira-letsencrypt:/etc/letsencrypt -v kira-certbot-webroot:/var/www/certbot certbot/certbot \
     renew --webroot -w /var/www/certbot --dry-run -q >/dev/null 2>&1; then
  say "Проверка автопродления пройдена."
else
  warn "Тестовое продление не прошло. Сертификат действует 90 дней; проверь: docker run --rm -v kira-letsencrypt:/etc/letsencrypt -v kira-certbot-webroot:/var/www/certbot certbot/certbot renew --webroot -w /var/www/certbot --dry-run"
fi
if [[ "$CRON" == 1 ]]; then
  if [[ ${EUID:-$(id -u)} -eq 0 && -d /etc/cron.d ]]; then
    printf '17 3,15 * * * root %s >/var/log/kira-certbot.log 2>&1\n' "$RENEW" > /etc/cron.d/kira-certbot
    chmod 644 /etc/cron.d/kira-certbot
    say "Автопродление включено (/etc/cron.d/kira-certbot, два раза в сутки)."
  else
    warn "Нет прав root или /etc/cron.d — добавь в cron вручную:  17 3,15 * * * $RENEW"
  fi
fi
say "Токен, .env и данные бота не менялись. Отключить HTTPS: bash https.sh --remove"
